#!/usr/bin/env bash
# Deploy the gateway to a server over ssh (platform track, Docker stage).
#
# Copies the pull-only prod compose file plus a generated `.env` to the
# server, then pulls the CI-built image from GitHub Packages and restarts
# the service. Nothing is built on the server.
#
# Gateway only: catalog-sync is a separate process on its own host and
# shares only the versioned DB artifact with the gateway (see
# docs/architecture.md); it is not part of this deploy.
#
# Configuration (all via environment):
#   DEPLOY_HOST          ssh target, e.g. user@example.com. Default: apps.lan.
#   DEPLOY_DIR           Remote directory. Default: /opt/stacks/pennyrouter.
#   COMPOSE_FILE         Local compose file to ship. Default: compose.prod.yaml.
#                        Must be pull-only (no `build:` section, CI-enforced).
#   REMOTE_COMPOSE       Name on the server. Default: compose.yaml, so plain
#                        `docker compose` finds it without -f.
#   DEPLOY_ENV_FILE      Optional. Copy this local file as the remote `.env`
#                        instead of generating one from the vars below.
#   HOST_PORT            Published port on the server. Default: 3000.
#   PORT                 Container port. Default: 3000.
#   IMAGE                Image to pull. Default: ghcr.io/lsk242/pennyrouter:latest.
#   OPENROUTER_BASE_URL  Upstream base URL. Default: https://openrouter.ai/api.
#   MODAL_BASE_URL       Pinned upstream for `modal/…` routes. Empty by
#                        default (those routes fail closed until set).
#   BASETEN_BASE_URL     Pinned upstream for `baseten/…` routes. Default:
#                        https://inference.baseten.co/v1.
#   GATEWAY_UI           Set to 1 to register the read-only GET /ui debug
#                        page. Empty by default (route does not exist).
#   SSH_OPTS             Extra options for ssh/scp, e.g. "-i ~/.ssh/id -p 2222".
#   DRY_RUN              Set to 1 to print what would run without touching
#                        the server.
#
# Usage:
#   DEPLOY_HOST=user@example.com ./scripts/deploy.sh
#   DEPLOY_HOST=user@example.com make deploy
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

DEPLOY_HOST="${DEPLOY_HOST:-apps.lan}"
DEPLOY_DIR="${DEPLOY_DIR:-/opt/stacks/pennyrouter}"
COMPOSE_FILE="${COMPOSE_FILE:-compose.dev.yaml}"
HOST_PORT="${HOST_PORT:-3000}"
PORT="${PORT:-3000}"
IMAGE="${IMAGE:-ghcr.io/lsk242/pennyrouter:latest}"
OPENROUTER_BASE_URL="${OPENROUTER_BASE_URL:-https://openrouter.ai/api}"
MODAL_BASE_URL="${MODAL_BASE_URL:-}"
BASETEN_BASE_URL="${BASETEN_BASE_URL:-https://inference.baseten.co/v1}"
GATEWAY_UI="${GATEWAY_UI:-}"
DRY_RUN="${DRY_RUN:-0}"

# shellcheck disable=SC2086
SSH=(ssh ${SSH_OPTS:-})
# shellcheck disable=SC2086
SCP=(scp ${SSH_OPTS:-})

SRC="$ROOT/$COMPOSE_FILE"
if [[ ! -f "$SRC" ]]; then
  echo "error: compose file not found: $SRC" >&2
  exit 1
fi
if grep -Eq '^[[:space:]]*build:' "$SRC"; then
  echo "error: $COMPOSE_FILE must be pull-only (no build: section)" >&2
  exit 1
fi

REMOTE_COMPOSE="${REMOTE_COMPOSE:-compose.yaml}"
ENV_FILE=""
cleanup() {
  if [[ -n "$ENV_FILE" && -z "${DEPLOY_ENV_FILE:-}" ]]; then
    rm -f "$ENV_FILE"
  fi
}
trap cleanup EXIT

if [[ -n "${DEPLOY_ENV_FILE:-}" ]]; then
  if [[ ! -f "$DEPLOY_ENV_FILE" ]]; then
    echo "error: DEPLOY_ENV_FILE not found: $DEPLOY_ENV_FILE" >&2
    exit 1
  fi
  ENV_FILE="$DEPLOY_ENV_FILE"
else
  ENV_FILE="$(mktemp)"
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/deploy.sh — do not edit by hand.
# Redeploy to change values (see the header of scripts/deploy.sh).
PORT=$PORT
HOST_PORT=$HOST_PORT
IMAGE=$IMAGE
OPENROUTER_BASE_URL=$OPENROUTER_BASE_URL
MODAL_BASE_URL=$MODAL_BASE_URL
BASETEN_BASE_URL=$BASETEN_BASE_URL
GATEWAY_UI=$GATEWAY_UI
EOF
fi

run() {
  if [[ "$DRY_RUN" == "1" ]]; then
    printf '+ %s\n' "$*"
  else
    "$@"
  fi
}

echo "--- deploying gateway to $DEPLOY_HOST:$DEPLOY_DIR (host port $HOST_PORT) ---"
if [[ "$DRY_RUN" == "1" && -z "${DEPLOY_ENV_FILE:-}" ]]; then
  echo "--- generated .env ---"
  cat "$ENV_FILE"
fi
run "${SSH[@]}" "$DEPLOY_HOST" "mkdir -p $DEPLOY_DIR"
run "${SCP[@]}" "$SRC" "$DEPLOY_HOST:$DEPLOY_DIR/$REMOTE_COMPOSE"
run "${SCP[@]}" "$ENV_FILE" "$DEPLOY_HOST:$DEPLOY_DIR/.env"
run "${SSH[@]}" "$DEPLOY_HOST" \
  "cd $DEPLOY_DIR && docker compose -f $REMOTE_COMPOSE pull && docker compose -f $REMOTE_COMPOSE up -d"
run "${SSH[@]}" "$DEPLOY_HOST" \
  "ok=0; for i in \$(seq 1 30); do if curl -fsS --connect-timeout 2 --max-time 5 http://localhost:$HOST_PORT/health; then ok=1; break; fi; sleep 2; done; [ \"\$ok\" = 1 ] || { echo 'deploy: gateway health check failed' >&2; exit 1; }"
echo "--- deployed: http://$DEPLOY_HOST:$HOST_PORT/health ---"
